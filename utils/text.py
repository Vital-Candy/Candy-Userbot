"""Работа с текстом для Telegram-сообщений."""
from __future__ import annotations

# Символы, которыми Telethon-Markdown размечает текст. В Telethon нет экранирования
# обратным слэшем, поэтому такие символы нельзя ни принимать в именах, ни выводить как есть.
MARKDOWN_SPECIAL = "*~`|[]()\\"
# Подсказка пользователю о запрещённых символах (для сообщений об ошибке).
MARKDOWN_SPECIAL_HINT = "* ~ ` | [ ] ( ) \\ и __"


def has_markdown_syntax(text: str) -> bool:
    """Есть ли в тексте символы разметки Telethon-Markdown (включая ``__``)."""
    return "__" in text or any(char in MARKDOWN_SPECIAL for char in text)


def escape_markdown(text: str) -> str:
    """Безопасно показывает произвольный текст в Markdown-сообщении.

    Разметочные символы заменяются похожими безопасными, ``__`` разделяется
    невидимым пробелом нулевой ширины. Обычный текст не меняется.
    """
    table = {
        "*": "∗",
        "~": "∼",
        "`": "ʼ",
        "|": "¦",
        "[": "⟦",
        "]": "⟧",
        "(": "⦅",
        ")": "⦆",
        "\\": "∖",
    }
    # Подстановка вместо удаления: текст остаётся читаемым, а разметка не срабатывает.
    safe = "".join(table.get(char, char) for char in text)
    # Цикл: после одной замены «___» даёт новую пару подчёркиваний, поэтому повторяем до устранения.
    while "__" in safe:
        safe = safe.replace("__", "_​_")
    return safe
